#!/usr/bin/env python3
"""Combine the independent packages' generated port data into the repository index."""

import argparse
import json
from pathlib import Path


def load_data(path):
    text = path.read_text()
    return json.loads(text[text.index("{") : text.rindex("}") + 1])


def render_index(root):
    categories = []
    ids = set()
    for manifest in sorted(root.glob("src/*_behaviors/package.xml")):
        package = manifest.parent
        data = load_data(package / "docs/behavior_index/behavior_index_data.js")
        if len(data["categories"]) != 1:
            raise ValueError(f"{package.name}: expected one package in its index")
        category = data["categories"][0]
        if category["folder"] != package.name:
            raise ValueError(f"{package.name}: wrong package in its index")
        for behavior in category["behaviors"]:
            if behavior["id"] in ids:
                raise ValueError(f"Duplicate Behavior ID: {behavior['id']}")
            ids.add(behavior["id"])
        categories.append(category)
    if not categories:
        raise ValueError("No Behavior packages found")
    return (
        "// Generated by tools/update_behavior_index.py. Do not edit by hand.\n"
        "window.BEHAVIOR_INDEX = "
        + json.dumps({"categories": categories}, indent=2, ensure_ascii=False)
        + ";\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail if the index is stale"
    )
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    target = root / "docs/behavior_index/behavior_index_data.js"
    rendered = render_index(root)
    if args.check:
        if target.read_text() != rendered:
            parser.error(
                "Repository index is stale. Run tools/update_behavior_index.py"
            )
    else:
        target.write_text(rendered)


if __name__ == "__main__":
    main()
