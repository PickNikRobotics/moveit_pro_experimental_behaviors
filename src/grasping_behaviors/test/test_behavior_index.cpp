/**
 * @file
 * @brief Keeps docs/behavior_index/behavior_index_data.js in step with the registered Behaviors.
 *
 * @details
 * Registers this package and writes every Behavior's ID, metadata and ports as JSON.
 * The index page shows what the code registers, not what a person typed.
 *
 * With UPDATE_BEHAVIOR_INDEX set, the test rewrites the data file. Without it, the test fails when the committed
 * file differs from the code. The check skips the C++ type names, which can differ between ROS distributions.
 */

namespace
{
constexpr auto kUpdateEnvVar = "UPDATE_BEHAVIOR_INDEX";
constexpr auto kTypeFieldMarker = "\"type\":";

/** @brief Escapes @p text as the body of a JSON string. */
std::string jsonEscape(const std::string& text)
{
  std::string out;
  for (const char c : text)
  {
    switch (c)
    {
      case '"':
        out += "\\\"";
        break;
      case '\\':
        out += "\\\\";
        break;
      case '\n':
        out += "\\n";
        break;
      case '\t':
        out += "\\t";
        break;
      case '\r':
        out += "\\r";
        break;
      default:
        if (static_cast<unsigned char>(c) < 0x20)
        {
          char buffer[8];
          std::snprintf(buffer, sizeof(buffer), "\\u%04x", static_cast<unsigned>(c));
          out += buffer;
        }
        else
        {
          out += c;
        }
    }
  }
  return out;
}

std::string quoted(const std::string& text)
{
  return "\"" + jsonEscape(text) + "\"";
}

std::string directionName(BT::PortDirection direction)
{
  switch (direction)
  {
    case BT::PortDirection::INPUT:
      return "input";
    case BT::PortDirection::OUTPUT:
      return "output";
    default:
      return "inout";
  }
}

std::string metadataValue(const BT::KeyValueVector& metadata, const std::string& key)
{
  for (const auto& [k, v] : metadata)
  {
    if (k == key)
    {
      return v;
    }
  }
  return "";
}

/** @brief Renders the data file: one JSON field per line, so the type lines can be dropped for comparison. */
std::string renderBehaviorIndex()
{
  auto node = std::make_shared<rclcpp::Node>("behavior_index_test");
  auto context = std::make_shared<moveit_pro::behaviors::BehaviorContext>(node);

  std::ostringstream out;
  out << "// Generated by test/test_behavior_index.cpp. Do not edit by hand.\n"
      << "// Regenerate it as described in docs/behavior_index/README.md.\n"
      << "window.BEHAVIOR_INDEX = {\n"
      << "  \"categories\": [\n";

  {
    BT::BehaviorTreeFactory factory;
    const std::set<std::string> builtins = factory.builtinNodes();
    grasping_behaviors::registerGraspingBehaviors(factory, context);

    std::map<std::string, BT::TreeNodeManifest> manifests;
    for (const auto& [id, manifest] : factory.manifests())
    {
      if (builtins.count(id) == 0)
      {
        manifests.emplace(id, manifest);
      }
    }

    out << "    {\n"
        << "      \"folder\": " << quoted("grasping_behaviors") << ",\n"
        << "      \"summary\": "
        << quoted("Filter graspable objects, read their shape, label the pick direction, and make grasp and place "
                  "candidates.")
        << ",\n"
        << "      \"behaviors\": [\n";
    std::size_t b = 0;
    for (const auto& [id, manifest] : manifests)
    {
      out << "        {\n"
          << "          \"id\": " << quoted(id) << ",\n"
          << "          \"node_type\": " << quoted(BT::toStr(manifest.type)) << ",\n"
          << "          \"subcategory\": "
          << quoted(metadataValue(manifest.metadata, moveit_pro::behaviors::kSubcategoryMetadataKey)) << ",\n"
          << "          \"description\": "
          << quoted(metadataValue(manifest.metadata, moveit_pro::behaviors::kDescriptionMetadataKey)) << ",\n"
          << "          \"ports\": [\n";
      const std::map<std::string, BT::PortInfo> ports(manifest.ports.begin(), manifest.ports.end());
      std::size_t p = 0;
      for (const auto& [name, info] : ports)
      {
        const bool has_default = !info.defaultValue().empty();
        out << "            {\n"
            << "              \"name\": " << quoted(name) << ",\n"
            << "              \"direction\": " << quoted(directionName(info.direction())) << ",\n"
            << "              " << kTypeFieldMarker << " " << quoted(info.typeName()) << ",\n"
            << "              \"default\": " << (has_default ? quoted(info.defaultValueString()) : "null") << ",\n"
            << "              \"description\": " << quoted(info.description()) << "\n"
            << "            }" << (++p < ports.size() ? "," : "") << "\n";
      }
      out << "          ]\n"
          << "        }" << (++b < manifests.size() ? "," : "") << "\n";
    }
    out << "      ]\n"
        << "    }\n";
  }
  out << "  ]\n"
      << "};\n";
  return out.str();
}

/** @brief Drops the lines that carry C++ type names, which are not stable across ROS distributions. */
std::vector<std::string> comparableLines(const std::string& text)
{
  std::vector<std::string> lines;
  std::istringstream stream(text);
  std::string line;
  while (std::getline(stream, line))
  {
    if (line.find(kTypeFieldMarker) == std::string::npos)
    {
      lines.push_back(line);
    }
  }
  return lines;
}
}  // namespace

TEST(BehaviorIndex, data_file_matches_registered_behaviors)
{
  const std::string rendered = renderBehaviorIndex();

  const char* update = std::getenv(kUpdateEnvVar);
  if (update != nullptr && std::string(update) != "" && std::string(update) != "0")
  {
    std::ofstream file(BEHAVIOR_INDEX_DATA_FILE, std::ios::trunc);
    ASSERT_TRUE(file.good()) << "Cannot write " << BEHAVIOR_INDEX_DATA_FILE;
    file << rendered;
    GTEST_SKIP() << "Rewrote " << BEHAVIOR_INDEX_DATA_FILE;
  }

  std::ifstream file(BEHAVIOR_INDEX_DATA_FILE);
  ASSERT_TRUE(file.good()) << "Cannot read " << BEHAVIOR_INDEX_DATA_FILE;
  std::stringstream committed;
  committed << file.rdbuf();

  const auto expected = comparableLines(rendered);
  const auto actual = comparableLines(committed.str());
  const std::size_t common = std::min(expected.size(), actual.size());
  for (std::size_t i = 0; i < common; ++i)
  {
    ASSERT_EQ(actual[i], expected[i]) << "The behavior index data is stale. Regenerate it as described in "
                                         "docs/behavior_index/README.md (first difference at comparable line "
                                      << i + 1 << ").";
  }
  ASSERT_EQ(actual.size(), expected.size()) << "The behavior index data is stale. Regenerate it as described in "
                                               "docs/behavior_index/README.md.";
}

int main(int argc, char** argv)
{
  rclcpp::init(argc, argv);
  testing::InitGoogleTest(&argc, argv);
  const int result = RUN_ALL_TESTS();
  rclcpp::shutdown();
  return result;
}
